export interface SubmitAttemptInput {
  assessmentId: string;
  studentId: string;
  source: EvidenceSource;
  /** Generated by the client. Retrying with the same key never creates a second attempt. */
  idempotencyKey: string;
  responses: Array<{ questionId: string; response: StudentResponse; selfConfidence?: SelfConfidence }>;
  /** When the student actually answered. Offline sync passes the original time. Defaults to now. */
  observedAt?: Date;
  actorId?: string;
  requestId?: string;
}

export interface ResponseOutcome {
  questionId: string;
  result: Evaluation["result"];
  reason: string;
  diagnosis: Diagnosis;
}

export interface SubmitAttemptResult {
  attemptId: string;
  /** True when this key was already processed; nothing new was written. */
  duplicate: boolean;
  /** Present for new submissions. A duplicate returns only stored results (no diagnosis). */
  responses: Array<Omit<ResponseOutcome, "diagnosis"> & { diagnosis?: Diagnosis }>;
}

/** How trustworthy and how reviewable a response is, by how it was obtained. */
function evidenceQuality(ev: Evaluation): { confidence: EvidenceConfidence; reviewStatus: EvidenceReviewStatus } {
  switch (ev.reason) {
    case "correct":
    case "wrong_option":
      return { confidence: "high", reviewStatus: "not_required" };
    case "blank":
      return { confidence: "high", reviewStatus: "not_required" };
    // Something a person typed or scanned that we could not interpret: a human must look at it.
    default:
      return { confidence: "low", reviewStatus: "pending" };
  }
}

/**
 * Records one student's answers to an assessment in a single transaction:
 * responses → evidence ledger → misconception diagnosis → mastery recomputation.
 * Either everything is saved or nothing is (CLAUDE.md §10). Safe to retry with the same key.
 * Callers (routes, sync) must already have checked that the actor may submit for this student.
 */
export async function submitAttempt(db: Db, input: SubmitAttemptInput): Promise<SubmitAttemptResult> {
  try {
    return await db.transaction((tx) => submitInTransaction(tx, input));
  } catch (err) {
    // Two requests with the same key racing: the loser finds the winner's attempt.
    if (isUniqueViolation(err)) {
      const existing = await findDuplicate(db, input);
      if (existing) return existing;
      throw conflict("This student has already submitted this assessment.");
    }
    throw err;
  }
}

async function findDuplicate(db: Db | Tx, input: SubmitAttemptInput): Promise<SubmitAttemptResult | undefined> {
  const [attempt] = await db.select().from(assessmentAttempts).where(eq(assessmentAttempts.syncId, input.idempotencyKey));
  if (!attempt) return undefined;
  if (attempt.assessmentId !== input.assessmentId || attempt.studentId !== input.studentId) {
    throw conflict("This idempotency key was already used for a different submission.");
  }
  const stored = await db.select().from(questionResponses).where(eq(questionResponses.attemptId, attempt.id));
  return { attemptId: attempt.id, duplicate: true, responses: stored.map((r) => ({ questionId: r.questionId, result: r.result, reason: r.resultReason })) };
}

async function submitInTransaction(tx: Tx, input: SubmitAttemptInput): Promise<SubmitAttemptResult> {
  const duplicate = await findDuplicate(tx, input);
  if (duplicate) return duplicate;

  const [assessment] = await tx.select().from(assessments).where(eq(assessments.id, input.assessmentId));
  if (!assessment) throw new AppError("not_found", "Assessment not found.");
  // Students answer only while it is open. A teacher may also key in, or approve, paper answers after it closes.
  // Work recorded offline may also arrive for an activity that was approved but never opened on the server.
  const teacherSource = input.source === "teacher_entered" || input.source === "paper_reviewed" || input.source === "offline_synced";
  const acceptsAnswers = assessment.status === "open" || (teacherSource && assessment.status === "closed") || (input.source === "offline_synced" && assessment.status === "approved") || (input.source === "practice_activity" && assessment.status === "closed" && assessment.ownerStudentId === input.studentId);
  if (!acceptsAnswers) throw conflict("This assessment is not open for answers.");

  const [enrolment] = await tx
    .select({ id: classEnrolments.id })
    .from(classEnrolments)
    .where(and(eq(classEnrolments.classId, assessment.classId), eq(classEnrolments.studentId, input.studentId), eq(classEnrolments.status, "active")));
  if (!enrolment) throw new AppError("forbidden", "This student is not in the assessment's class.");

  const allowed = await tx.select({ questionId: assessmentQuestions.questionId }).from(assessmentQuestions).where(eq(assessmentQuestions.assessmentId, assessment.id));
  const allowedIds = new Set(allowed.map((a) => a.questionId));
  const seen = new Set<string>();
  for (const r of input.responses) {
    if (!allowedIds.has(r.questionId)) throw new AppError("validation_error", "A response is for a question that is not in this assessment.");
    if (seen.has(r.questionId)) throw new AppError("validation_error", "A question was answered more than once.");
    seen.add(r.questionId);
  }
  if (input.responses.length === 0) throw new AppError("validation_error", "No responses were submitted.");

  const bank = await loadBankQuestions(tx, input.responses.map((r) => r.questionId));
  const rules = await loadRules(tx);
  const now = input.observedAt ?? new Date();

  const [attempt] = await tx
    .insert(assessmentAttempts)
    .values({ assessmentId: assessment.id, studentId: input.studentId, submissionSource: input.source, syncId: input.idempotencyKey, status: "submitted", submittedAt: new Date() })
    .returning();

  const outcomes: ResponseOutcome[] = [];
  const touchedConcepts = new Set<string>();

  for (const item of input.responses) {
    const question = bank.get(item.questionId) as BankQuestion;
    const evaluation = evaluateResponse(question, item.response);
    const quality = evidenceQuality(evaluation);
    const rule = matchMisconception(question, item.response, evaluation, rules);

    const [response] = await tx
      .insert(questionResponses)
      .values({
        attemptId: attempt!.id,
        questionId: question.id,
        responseData: item.response as unknown as Record<string, unknown>,
        selfConfidence: item.selfConfidence ?? null,
        result: evaluation.result,
        resultReason: evaluation.reason,
      })
      .returning();

    const [evidence] = await tx
      .insert(assessmentEvidence)
      .values({
        studentId: input.studentId,
        conceptId: question.conceptId,
        questionResponseId: response!.id,
        source: input.source,
        result: evaluation.result,
        difficulty: question.difficulty,
        selfConfidence: item.selfConfidence ?? null,
        confidence: quality.confidence,
        reviewStatus: quality.reviewStatus,
        relationship: "primary",
        matchedMisconceptionPatternId: rule?.id ?? null,
        observedAt: now,
      })
      .returning();
    touchedConcepts.add(question.conceptId);

    // A correct answer also shows the prerequisite skills it used. A wrong answer does not blame them.
    if (evaluation.result === "correct") {
      for (const conceptId of question.alsoAssesses ?? []) {
        await tx.insert(assessmentEvidence).values({
          studentId: input.studentId,
          conceptId,
          questionResponseId: response!.id,
          source: input.source,
          result: "correct",
          difficulty: question.difficulty,
          selfConfidence: item.selfConfidence ?? null,
          confidence: "medium",
          reviewStatus: "not_required",
          relationship: "also_assesses",
          observedAt: now,
        });
        touchedConcepts.add(conceptId);
      }
    }

    // Diagnosis uses the student's history for the matched rule.
    let priorSignals: PriorSignal[] = [];
    let followUp: { questionId: string; questionKey: string } | undefined;
    let followUpAsked = false;
    let followUpCorrect = false;
    if (rule) {
      const prior = await tx
        .select({
          questionId: questionResponses.questionId,
          evidenceId: misconceptionObservations.evidenceId,
          selfConfidence: questionResponses.selfConfidence,
          status: misconceptionObservations.status,
        })
        .from(misconceptionObservations)
        .innerJoin(assessmentEvidence, eq(assessmentEvidence.id, misconceptionObservations.evidenceId))
        .innerJoin(questionResponses, eq(questionResponses.id, assessmentEvidence.questionResponseId))
        .where(and(eq(misconceptionObservations.studentId, input.studentId), eq(misconceptionObservations.patternId, rule.id)));
      priorSignals = prior.map((p) => ({ questionId: p.questionId, evidenceId: p.evidenceId, selfConfidence: p.selfConfidence ?? undefined, status: p.status }));

      const [fq] = await tx.select({ id: questions.id, key: questions.key }).from(questions).where(eq(questions.key, rule.followUpQuestionKey));
      if (fq) {
        followUp = { questionId: fq.id, questionKey: fq.key };
        const answered = await tx
          .select({ result: questionResponses.result, attemptStudent: assessmentAttempts.studentId })
          .from(questionResponses)
          .innerJoin(assessmentAttempts, eq(assessmentAttempts.id, questionResponses.attemptId))
          .where(and(eq(questionResponses.questionId, fq.id), eq(assessmentAttempts.studentId, input.studentId), ne(questionResponses.id, response!.id)));
        followUpAsked = answered.length > 0;
        followUpCorrect = answered.some((a) => a.result === "correct");
      }
    }

    const diagnosis = diagnose({
      studentId: input.studentId,
      conceptId: question.conceptId,
      current: {
        questionId: question.id,
        evidenceId: evidence!.id,
        result: evaluation.result,
        selfConfidence: item.selfConfidence,
        evidenceConfidence: quality.confidence,
        evidenceReviewStatus: quality.reviewStatus,
        rule,
      },
      priorSignals,
      followUp,
      followUpAnsweredCorrectly: followUpCorrect,
      followUpAlreadyAsked: followUpAsked,
    });

    if (rule && diagnosis.observationStatus) {
      await tx.insert(misconceptionObservations).values({ studentId: input.studentId, conceptId: question.conceptId, patternId: rule.id, evidenceId: evidence!.id, status: diagnosis.observationStatus });
      // Once corroborated, earlier single observations of the same pattern become "likely" too.
      if (diagnosis.observationStatus === "likely") {
        await tx
          .update(misconceptionObservations)
          .set({ status: "likely" })
          .where(and(eq(misconceptionObservations.studentId, input.studentId), eq(misconceptionObservations.patternId, rule.id), eq(misconceptionObservations.status, "candidate")));
      }
    }

    outcomes.push({ questionId: question.id, result: evaluation.result, reason: evaluation.reason, diagnosis: stripInternal(diagnosis) });
  }

  for (const conceptId of touchedConcepts) await recomputeMastery(tx, input.studentId, conceptId, { now });

  await recordAudit(tx, {
    actorId: input.actorId ?? null,
    action: "attempt.submit",
    entityType: "assessment_attempt",
    entityId: attempt!.id,
    metadata: { assessmentId: assessment.id, source: input.source, responses: input.responses.length },
    ...(input.requestId ? { requestId: input.requestId } : {}),
  });

  return { attemptId: attempt!.id, duplicate: false, responses: outcomes };
}

function stripInternal<T extends { observationStatus?: unknown }>(d: T): Omit<T, "observationStatus"> {
  const { observationStatus: _omit, ...rest } = d;
  return rest;
}

/** Evidence rows for one attempt, for the "Why?" drill-down. */
export async function evidenceForAttempt(db: Db, attemptId: string) {
  return db
    .select({ evidence: assessmentEvidence })
    .from(assessmentEvidence)
    .innerJoin(questionResponses, eq(questionResponses.id, assessmentEvidence.questionResponseId))
    .where(eq(questionResponses.attemptId, attemptId));
}

